#!/usr/bin/env node
// Writes webapp/src/abi.ts from the Solidity interface with `forge inspect`.
// The result is committed, so you need this only if the interface changes (it should not).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const abi = execFileSync("forge", ["inspect", "IBillSplitter", "abi", "--json"], {
  cwd: join(root, "contracts"),
  encoding: "utf8",
});
const body = JSON.stringify(JSON.parse(abi), null, 2);
writeFileSync(
  join(root, "webapp/src/abi.ts"),
  `// GENERATED by scripts/gen-abi.mjs from contracts/src/interfaces/IBillSplitter.sol. Do not edit by hand.\n` +
    `export const billSplitterAbi = ${body} as const;\n`,
);
console.log("ABI written to webapp/src/abi.ts");
